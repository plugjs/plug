import { install } from '@plugjs/plug/pipe'

import { Coverage } from './coverage.ts'

import type { SourceMapBias } from './analysis.ts'

/** Options for analysing coverage and checking node coverage thresholds. */
export interface CoverageOptions {
  /** The bias for source map analysis (defaults to `least_upper_bound`). */
  sourceMapBias?: SourceMapBias
  /** Minimum _overall_ coverage (as a percentage, defaults to 50). */
  minimumCoverage?: number,
  /** Optimal _overall_ coverage (defaults to the rounded midpoint of minimumCoverage and 100: 75). */
  optimalCoverage?: number,
  /** Minimum _per-file_ coverage (defaults to minimumCoverage: 50). */
  minimumFileCoverage?: number,
  /** Optimal _per-file_ coverage (defaults to the rounded midpoint of minimumFileCoverage and 100: 75). */
  optimalFileCoverage?: number,
  /** Include uncovered line ranges in console reports (defaults to `false`). */
  reportUncoveredLines?: boolean
}

export interface CoverageReportOptions extends CoverageOptions {
  /** Directory for report.json, index.html, and the report.js data file. */
  reportDir: string,
}

declare module '@plugjs/plug' {
  export interface Pipe {
    /**
     * Analyse coverage using files generated by V8/Node.js.
     *
     * @param coverageDir The directory where the `coverage-XXX.json` files
     *                    generated by V8/Node.js can be found.
     */
    coverage(coverageDir: string): Promise<undefined>
    /**
     * Analyse coverage using files generated by V8/Node.js and produce an HTML
     * report in the directory specified in `options`.
     *
     * @param coverageDir The directory where the `coverage-XXX.json` files
     *                    generated by V8/Node.js can be found.
     * @param options Coverage thresholds and the report output directory.
     * @returns A pipe containing the generated report files.
     */
    coverage(coverageDir: string, options: CoverageReportOptions): Pipe
    /**
     * Analyse coverage using files generated by V8/Node.js.
     *
     * @param coverageDir The directory where the `coverage-XXX.json` files
     *                    generated by V8/Node.js can be found.
     * @param options Coverage thresholds and console reporting options.
     */
    coverage(coverageDir: string, options: CoverageOptions): Promise<undefined>
  }
}

/* ========================================================================== *
 * INSTALLATION / IMPLEMENTATION                                              *
 * ========================================================================== */

install('coverage', Coverage)
